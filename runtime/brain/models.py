from __future__ import annotations

from dataclasses import dataclass, field
from datetime import datetime
from typing import Any
from uuid import uuid4

from runtime.brain.enums import (
    IntentType,
    PlanStatus,
    ReflectionStatus,
    SkillType,
    TaskAction,
)

from runtime.brain.task import Task


# ==========================================================
# PLAN
# ==========================================================

@dataclass(slots=True)
class Plan:
    """
    Represents an execution plan generated by the Planner.
    """

    id: str = field(default_factory=lambda: str(uuid4()))

    goal: str = ""

    intent: IntentType = IntentType.UNKNOWN

    tasks: list[Task] = field(default_factory=list)

    status: PlanStatus = PlanStatus.CREATED

    metadata: dict[str, Any] = field(default_factory=dict)

    summary: str = ""

    created_at: datetime = field(default_factory=datetime.utcnow)

    started_at: datetime | None = None

    finished_at: datetime | None = None

    @property
    def completed_tasks(self) -> int:
        return sum(task.status.name == "SUCCESS" for task in self.tasks)

    @property
    def total_tasks(self) -> int:
        return len(self.tasks)

    @property
    def progress(self) -> float:
        if not self.tasks:
            return 0.0

        return self.completed_tasks / len(self.tasks)


# ==========================================================
# INTENT TASK
# ==========================================================

@dataclass(slots=True)
class IntentTask:
    """
    A task identified by the IntentClassifier.

    These are high-level tasks that the Planner
    converts into executable Plan tasks.
    """

    skill: SkillType

    action: TaskAction

    parameters: dict[str, Any] = field(default_factory=dict)


# ==========================================================
# INTENT RESULT
# ==========================================================

@dataclass(slots=True)
class IntentResult:
    """
    Output produced by the IntentClassifier.

    Represents the user's intent before planning.
    """

    # User's overall objective
    goal: str

    # High-level intent category
    intent: IntentType

    # Tasks identified by the LLM
    tasks: list[IntentTask] = field(default_factory=list)

    # LLM confidence
    confidence: float = 0.0

    # Optional reasoning
    reasoning: str = ""

    # Original user command
    command: str = ""

    # Raw LLM response (useful for debugging)
    raw_response: dict[str, Any] | None = None


# ==========================================================
# EXECUTION RESULT
# ==========================================================

@dataclass(slots=True)
class ExecutionResult:
    """
    Output from the Executor.
    """

    success: bool

    completed_tasks: int = 0

    failed_tasks: int = 0

    message: str = ""

    data: Any = None


# ==========================================================
# REFLECTION RESULT
# ==========================================================

@dataclass(slots=True)
class ReflectionResult:
    """
    Output from the Reflection Engine.
    """

    status: ReflectionStatus

    should_retry: bool = False

    message: str = ""

    recommendations: list[str] = field(default_factory=list)

    execution: ExecutionResult | None = None
