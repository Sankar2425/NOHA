from __future__ import annotations

from abc import ABC, abstractmethod
from typing import Any

from runtime.tools.tool_registry import ToolRegistry


class BaseSkill(ABC):
    """
    Base class for all runtime skills.

    A Skill is responsible for orchestrating one domain by
    preparing payloads and invoking one or more tools.

    Skills SHOULD:
    - Validate task payloads
    - Prepare tool payloads
    - Call one or more tools
    - Return execution results

    Skills SHOULD NOT:
    - Classify user intent
    - Plan execution
    - Manage Brain state
    - Access RuntimeEngine
    """

    name: str = ""
    description: str = ""

    def __init__(self, tool_registry: ToolRegistry) -> None:
        self.tools = tool_registry

    @abstractmethod
    async def execute(self, task: Any) -> dict:
        """
        Execute a planner task.

        Parameters
        ----------
        task
            Task object generated by the Planner.

        Returns
        -------
        dict
            Standard execution result.
        """
        raise NotImplementedError

    def get_tool(self, name: str):
        """
        Retrieve a registered tool.

        Raises
        ------
        KeyError
            If the tool is not registered.
        """
        tool = self.tools.get(name)

        if tool is None:
            raise KeyError(f"Tool '{name}' is not registered.")

        return tool